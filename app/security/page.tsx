'use client';
import { useEffect, useState, type FormEvent } from 'react';
import { useRouter } from 'next/navigation';
import { DemoEntry } from '../../src/components/auth/demo-entry';
import { AuthShell } from '../../src/components/auth/auth-shell';
import { createBrowserSupabaseClient } from '../../src/lib/supabase/browser';

export default function SecurityPage() {
  const router=useRouter();
  const [factor,setFactor]=useState('');
  const [ready,setReady]=useState(false);
  const [busy,setBusy]=useState(false);
  const [qr,setQr]=useState('');
  const [secret,setSecret]=useState('');
  const [code,setCode]=useState('');
  const [error,setError]=useState('');
  useEffect(()=>{
    let active=true;
    void (async()=>{
      try {
        const client=createBrowserSupabaseClient();
        const user=await client.auth.getUser();
        if(user.error||!user.data.user){router.replace('/login');return;}
        const factors=await client.auth.mfa.listFactors();
        if(factors.error)throw factors.error;
        if(active){setFactor(factors.data.totp.find(f=>f.status==='verified')?.id??'');setReady(true);}
      }catch{if(active)setError('Could not load security verification. Refresh to try again.');}
    })();
    return()=>{active=false};
  },[router]);
  async function enroll(){
    if(busy)return;setBusy(true);setError('');
    try {
      const client=createBrowserSupabaseClient();
      const factors=await client.auth.mfa.listFactors();
      if(factors.error)throw factors.error;
      for(const f of factors.data.all.filter(f=>f.factor_type==='totp'&&f.status==='unverified')) {
        const removed=await client.auth.mfa.unenroll({factorId:f.id});if(removed.error)throw removed.error;
      }
      const {data,error}=await client.auth.mfa.enroll({factorType:'totp',issuer:'福 bank',friendlyName:'Bank authenticator'});
      if(error)throw error;
      setFactor(data.id);setQr(data.totp.qr_code);setSecret(data.totp.secret);
    }catch{setError('Could not set up your authenticator. Please try again.');}finally{setBusy(false);}
  }
  async function verify(event:FormEvent){
    event.preventDefault();if(busy||!/^\d{6}$/.test(code))return;setBusy(true);setError('');
    try {
      const client=createBrowserSupabaseClient();
      const {error}=await client.auth.mfa.challengeAndVerify({factorId:factor,code});
      if(error)throw error;
      setCode('');setSecret('');setQr('');router.replace('/banking');router.refresh();
    }catch{setCode('');setError('That code could not be verified. Try the current code from your authenticator.');}finally{setBusy(false);}
  }
  return <AuthShell><span className="auth-mode-label">ACCOUNT SECURITY</span><h1 className="auth-title">Verify it’s you.</h1>
    <p className="auth-intro">Use your authenticator app to protect your account.</p>
    {!ready&&!error?<p role="status">Loading security settings…</p>:null}
    {ready&&!factor?<button className="auth-submit" disabled={busy} onClick={()=>void enroll()}>Set up authenticator</button>:null}
    {qr?<div className="my-4 rounded-xl border border-slate-200 p-4"><p className="text-sm">Scan this code with your authenticator app.</p>
      {/* QR is generated by the authenticated provider and rendered as an image, never injected markup. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={qr.startsWith('data:image/')?qr:'data:image/svg+xml;charset=utf-8,'+encodeURIComponent(qr)} alt="Authenticator setup QR code" width={220} height={220}/>
      <details><summary className="cursor-pointer text-sm">Enter a setup key instead</summary><code className="break-all text-sm">{secret}</code></details>
      <p className="mt-2 text-xs text-slate-600">Keep this setup key safe. If you lose your authenticator, contact support for identity-verified recovery.</p></div>:null}
    {factor?<form className="auth-form" onSubmit={verify}><div className="auth-field"><label htmlFor="auth-code">Authenticator code</label>
      <input id="auth-code" className="auth-input" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required value={code} onChange={e=>setCode(e.target.value.replace(/\D/g,''))}/></div>
      <button className="auth-submit" disabled={busy||code.length!==6}>{busy?'Verifying…':'Verify and continue'}</button></form>:null}
    {error?<p role="alert" className="auth-feedback auth-feedback-error">{error}</p>:null}
    <div className="auth-switch"><button type="button" onClick={async()=>{const result=await createBrowserSupabaseClient().auth.signOut({scope:'local'});if(result.error){setError('Could not sign out. Please retry.');return;}router.replace('/login');router.refresh();}}>Sign out</button></div><div className="auth-switch"><DemoEntry className="underline"/></div>
  </AuthShell>;
}
